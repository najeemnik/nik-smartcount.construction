<?php
/**
 * One-time setup helper for an offline / LAN installation (a laptop used as the
 * office server). Run it from a terminal on that machine — never from the browser:
 *
 *     php api/setup-offline.php
 *
 * It only prepares local files; it never touches MySQL, existing data, or a public host:
 *   1. api/.secrets/offline.php   (local mode + trusted LAN host names)
 *   2. api/.secrets/database.php  (only if it does not exist yet, from the prompts)
 *   3. api/.secrets/email.php     (falls back to email MFA off for this machine)
 *   4. api/.secrets/install.key   (one-time installer key, printed once)
 *
 * Existing files are never overwritten. Delete the installer key after setup.
 */
if (PHP_SAPI !== 'cli') { http_response_code(404); echo "Run this from the terminal.\n"; exit; }

$secretDir = __DIR__ . '/.secrets';
if (!is_dir($secretDir) || !is_writable($secretDir)) {
    fwrite(STDERR, "Folder api/.secrets is missing or not writable.\n");
    exit(1);
}

function ask(string $question, string $default = ''): string {
    $suffix = $default !== '' ? " [$default]" : '';
    fwrite(STDOUT, $question . $suffix . ': ');
    $line = trim((string)fgets(STDIN));
    return $line !== '' ? $line : $default;
}

function writePrivate(string $path, string $contents, string $label): void {
    if (is_file($path)) { fwrite(STDOUT, "• $label already exists — kept unchanged.\n"); return; }
    $previous = umask(0077);
    $ok = file_put_contents($path, $contents) !== false;
    umask($previous);
    if (!$ok) { fwrite(STDERR, "Could not write $label.\n"); exit(1); }
    fwrite(STDOUT, "• $label created.\n");
}

fwrite(STDOUT, "NiK Smart Count — offline/LAN setup\n");
fwrite(STDOUT, "This machine will serve the app to devices on the same network.\n\n");

$lanIp = '';
foreach ((array)@gethostbynamel(gethostname() ?: 'localhost') as $candidate) {
    if (filter_var($candidate, FILTER_VALIDATE_IP) && !str_starts_with($candidate, '127.')) { $lanIp = $candidate; break; }
}
$hostName = strtolower(ask('Name this laptop should answer to on the LAN', 'nikbox.local'));
$dbHost  = ask('MySQL host', '127.0.0.1');
$dbPort  = ask('MySQL port', '3306');
$dbName  = ask('Database name', 'nsc_offline');
$dbUser  = ask('Database user', 'nsc');
$dbPass  = ask('Database password');

$quote = static fn($v) => var_export((string)$v, true);

writePrivate(
    $secretDir . '/offline.php',
    "<?php\n// Local/LAN profile generated by setup-offline.php\nreturn " . var_export([
        'enabled' => true,
        'trustedHosts' => array_values(array_unique(array_filter([$hostName, 'localhost', '127.0.0.1', $lanIp]))),
        'allowOtherOrigins' => false,
        'emailFallback' => 'auto',
    ], true) . ";\n",
    'api/.secrets/offline.php'
);

writePrivate(
    $secretDir . '/database.php',
    "<?php\nreturn ['HOST' => {$quote($dbHost)}, 'PORT' => {$quote($dbPort)}, 'NAME' => {$quote($dbName)}, 'USER' => {$quote($dbUser)}, 'PASS' => {$quote($dbPass)}];\n",
    'api/.secrets/database.php'
);

writePrivate(
    $secretDir . '/email.php',
    "<?php\n// Offline laptop: no mail transport, the code step is skipped inside local mode only.\nreturn ['enabled' => false, 'from' => 'security@nik-smartcount.com'];\n",
    'api/.secrets/email.php'
);

$keyFile = $secretDir . '/install.key';
if (is_file($keyFile)) {
    fwrite(STDOUT, "• api/.secrets/install.key already exists — kept unchanged.\n");
} else {
    $key = 'NSC-' . bin2hex(random_bytes(24));
    writePrivate($keyFile, $key . "\n", 'api/.secrets/install.key');
    fwrite(STDOUT, "\n  Installation key (use once on /installer.php, then delete the file):\n  $key\n");
}

fwrite(STDOUT, "\nNext steps\n");
fwrite(STDOUT, "1. Start the web server (Apache on XAMPP) and open http://$hostName/installer.php\n");
fwrite(STDOUT, "   (or http://" . ($lanIp ?: '<laptop-ip>') . "/installer.php)\n");
fwrite(STDOUT, "2. Paste the installation key, keep the database values above, create the owner account.\n");
fwrite(STDOUT, "3. Phones/other laptops on the same Wi-Fi open the same address and sign in with\n");
fwrite(STDOUT, "   the accounts the owner creates in the workspace (per-permission).\n");
fwrite(STDOUT, "4. Delete api/.secrets/install.key afterwards, and keep api/.secrets/ backed up.\n");
